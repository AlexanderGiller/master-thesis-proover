def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parts", default="all")
    ap.add_argument("--reps", type=int, default=3)
    args = ap.parse_args()
    parts = (
        {"runs", "noatp", "internal", "mutation", "inputs", "extra", "coverage", "tables"}
        if args.parts == "all"
        else set(args.parts.split(","))
    )
    OUT.mkdir(parents=True, exist_ok=True)
    GEN.mkdir(parents=True, exist_ok=True)

    if "runs" in parts:
        info = env_info()
        info["reps"] = args.reps
        write(OUT / "env.json", json.dumps(info, indent=1))
        part_runs(args.reps)
    if "noatp" in parts:
        part_runs(1, tag="noatp", env={"EXTERNAL_ATP_COMMAND": "/nonexistent/prover"})
    if "internal" in parts:
        part_internal()
    if "mutation" in parts:
        from src.deep_recursion import run_with_larger_stack

        run_with_larger_stack(part_mutation)
    if "inputs" in parts:
        part_inputs()
    if "extra" in parts:
        part_extra()
    if "coverage" in parts:
        part_coverage()
    if "tables" in parts:
        make_tables()
        for f, g in (
            ("internal.json", tables_internal),
            ("mutation.json", tables_mutation),
            ("inputs.json", tables_inputs),
            ("coverage.json", tables_coverage),
        ):
            if (OUT / f).exists():
                g()
        if (ROOT / "results" / "extra" / "results.csv").exists():
            tables_extra()


if __name__ == "__main__":
    main()
