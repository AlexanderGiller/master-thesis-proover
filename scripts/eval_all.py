def _slots(node):
    """Yield (getter, setter) for every sub-formula slot below node (formula level only)."""
    from src.parser.ast_nodes import BinaryFormula, JunctionFormula, Negation, QuantifiedFormula

    if isinstance(node, Negation):
        yield (lambda n=node: n.formula, lambda v, n=node: setattr(n, "formula", v))
        yield from _slots(node.formula)
    elif isinstance(node, BinaryFormula):
        yield (lambda n=node: n.left, lambda v, n=node: setattr(n, "left", v))
        yield (lambda n=node: n.right, lambda v, n=node: setattr(n, "right", v))
        yield from _slots(node.left)
        yield from _slots(node.right)
    elif isinstance(node, JunctionFormula):
        for i in range(len(node.operands)):
            yield (
                lambda n=node, i=i: n.operands[i],
                lambda v, n=node, i=i: n.operands.__setitem__(i, v),
            )
            yield from _slots(node.operands[i])
    elif isinstance(node, QuantifiedFormula):
        yield (lambda n=node: n.formula, lambda v, n=node: setattr(n, "formula", v))
        yield from _slots(node.formula)


def _nodes(node):
    yield node
    for g, _ in _slots(node):
        yield g()


def apply_operator(op: str, step, steps, rng):
    """Mutate `step` in place. Returns True if the operator was applicable."""
    from src.parser.ast_nodes import (
        Atom,
        BinaryFormula,
        Equality,
        JunctionFormula,
        Negation,
        QuantifiedFormula,
    )
    from src.var_mapping import BinaryConnective, InferenceStatus, Quantifier

    f = step.formula
    if op == "flip_connective":
        js = [n for n in _nodes(f) if isinstance(n, JunctionFormula)]
        if not js:
            return False
        n = rng.choice(js)
        n.connective = (
            BinaryConnective.OR if n.connective == BinaryConnective.AND else BinaryConnective.AND
        )
        return True
    if op == "flip_implication":
        bs = [n for n in _nodes(f) if isinstance(n, BinaryFormula) and str(n.connective) == "=>"]
        if not bs:
            return False
        n = rng.choice(bs)
        n.left, n.right = n.right, n.left
        return True
    if op == "swap_quantifier":
        qs = [n for n in _nodes(f) if isinstance(n, QuantifiedFormula)]
        if not qs:
            return False
        n = rng.choice(qs)
        n.quantifier = (
            Quantifier.EXISTENTIAL if n.quantifier == Quantifier.UNIVERSAL else Quantifier.UNIVERSAL
        )
        return True
    if op == "negate_atom":
        slots = [(g, s) for g, s in _slots(f) if isinstance(g(), (Atom, Equality))]
        if isinstance(f, (Atom, Equality)):
            step.formula = Negation(f)
            return True
        if not slots:
            return False
        g, s = rng.choice(slots)
        s(Negation(g()))
        return True
    if op == "remove_parent":
        if len(step.inference.parents) < 2:
            return False
        del step.inference.parents[rng.randrange(len(step.inference.parents))]
        return True
    if op == "redirect_parent":
        names = [
            s.name for s in steps if s.name != step.name and s.name not in step.inference.parents
        ]
        earlier = []
        for s in steps:
            if s.name == step.name:
                break
            earlier.append(s.name)
        names = [n for n in earlier if n not in step.inference.parents]
        if not names or not step.inference.parents:
            return False
        step.inference.parents[rng.randrange(len(step.inference.parents))] = rng.choice(names)
        return True
    if op == "status_cth":
        from src.parser.ast_nodes import StatusInfo

        for it in step.inference.info:
            if isinstance(it, StatusInfo):
                it.status = InferenceStatus.CTH
                return True
        return False
    return False


