def part_mutation(per_op: int = 2, max_steps: int = 80) -> None:
    import copy

    import main as V
    from src.checker.external_atp_checker import validate_step_with_atp

    V.DEBUG_PROOF_FLOW = False
    runs = [
        r
        for r in load("runs")
        if r["group"] in ("PRV",)
        and is_official(r)
        and r["expected"] == "CORRECT"
        and verdict(r) == "VerifiedGood"
        and len(r.get("steps", [])) <= max_steps
    ]
    rng = random.Random(2026)
    orig_load = V.load_proof
    rows = []
    try:
        for r in runs:
            base = orig_load(r["proof"])
            elig = [
                s
                for s in base.steps
                if s.inference
                and str(s.inference.rule) not in ("skolemize", "negated_conjecture")
                and s.role not in ("axiom", "conjecture")
                and str(s.inference.status) == "thm"
            ]
            for op in OPERATORS:
                tried = 0
                cand = elig[:]
                rng.shuffle(cand)
                for s0 in cand:
                    if tried >= per_op:
                        break
                    try:
                        mp = copy.deepcopy(base)
                    except RecursionError:
                        break
                    s = next(x for x in mp.steps if x.name == s0.name)
                    if not apply_operator(op, s, mp.steps, rng):
                        continue
                    tried += 1
                    V.load_proof = lambda p, mp=mp: mp
                    try:
                        res = V.check_proof_file(r["proof"], r["problem"])
                        killed = not res["all_ok"]
                    except Exception:  # noqa: BLE001
                        killed = True
                    V.load_proof = orig_load
                    entailed = None
                    if not killed:
                        by = {x.name: x for x in mp.steps}
                        try:
                            ok, _ = validate_step_with_atp(
                                s.formula,
                                [by[p].formula for p in s.inference.parents if p in by],
                                10.0,
                            )
                        except Exception:  # noqa: BLE001
                            ok = "unknown"
                        entailed = ok
                    rows.append(
                        dict(
                            proof=r["name"],
                            op=op,
                            step=s.name,
                            rule=str(s.inference.rule),
                            killed=killed,
                            survivor_entailed=str(entailed),
                        )
                    )
            print("[mutation]", r["name"], len(rows), flush=True)
    finally:
        V.load_proof = orig_load
    write(OUT / "mutation.json", json.dumps(rows))


